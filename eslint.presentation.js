// dynamic import(), and the data-fetching / state / router import bans — they
// don't describe this project (Lynk talks to Supabase from screens on purpose).
//
// ─── Two tiers ──────────────────────────────────────────────────────────────
//
// shadcn components are SOURCE FILES in this repo (`npx shadcn add` copies them
// into src/components/ui/). That source legitimately contains raw <button> and
// <table>, style={{ transform }}, `text-white` in the destructive variants and
// `bg-black/50` for dialog scrims. Holding it to the full ruleset would make
// every `shadcn add` produce un-committable code.
