// ─── Class-discipline rules ────────────────────────────────────────────────
//
// The theme is a set of CSS custom properties consumed through Tailwind utility
// names, so the failure mode is a class that resolves to a colour the theme does
// not control. Enforced as regexes over string literals: the published Tailwind
// ESLint plugins are v3-era and read a tailwind.config.js that no longer exists
// under v4.

// Arbitrary values that carry a COLOUR: bg-[#1677ff], border-[oklch(0.7_0.2_250)].
// NOT a general arbitrary-value ban — w-[340px] and max-h-[60vh] stay legal.
//
// The oklch / oklab / color-mix arms carry a negative lookahead: an arbitrary
// value is only a theme bypass if the colour it names is a LITERAL. A colour
// computed FROM a token still moves when the token moves, so
//   bg-[color-mix(in_oklch,var(--secondary),var(--foreground)_5%)]
// is allowed, while bg-[oklch(0.7_0.2_250)] is not. The #/rgb/hsl arms are
// unconditional: those forms cannot reference a token.
const ARBITRARY_COLOUR =
  "-\\[(?:#|rgb\\(|rgba\\(|hsl\\(|hsla\\(" +
  "|(?:oklch|oklab|color-mix)\\((?![^\\]]*var\\(--)" +
  ")";

// Raw palette utilities: bg-blue-500, text-zinc-700, border-slate-200. This is
// what makes "change a token and every screen moves" true.
const PALETTE_PREFIX =
  "(?:bg|text|border|ring|fill|stroke|shadow|from|via|to|divide|outline|decoration|accent|caret|placeholder)";
const PALETTE_HUE =
  "(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)";
const RAW_PALETTE = `\\b${PALETTE_PREFIX}-${PALETTE_HUE}-\\d{2,3}\\b`;

// Literal colours anywhere in a .tsx. AUTHORED ONLY — chart.tsx legitimately
// contains selectors like [&_.recharts-dot[stroke='#fff']], which target
// recharts' own DOM and are not a theme bypass.
const LITERAL_COLOUR = "(?:#[0-9a-fA-F]{3,8}\\b|\\b(?:rgb|rgba|hsl|hsla|oklch|oklab|color-mix)\\()";

// bg-white / text-black. AUTHORED ONLY — the registry uses text-white in the
// destructive variants and bg-black/50 for dialog and sheet scrims. One array
// entry, so it can be deleted in one line if scrims are worth the exception.
const HARDCODED_BW = `\\b${PALETTE_PREFIX}-(?:white|black)\\b`;

const THEME_FILE = "src/styles/tokens.css";

const ARBITRARY_COLOUR_MESSAGE =
  "No arbitrary colour values. Use a semantic token: bg-primary, text-muted-foreground, border-input.";
const RAW_PALETTE_MESSAGE = `No raw palette utilities (bg-blue-500). Use a semantic token, or add one to ${THEME_FILE}.`;

/** Build a matching pair of selectors: plain strings and template chunks. */
const stringMatchers = (pattern, message) => [
  { selector: `Literal[value=/${pattern}/]`, message },
  { selector: `TemplateElement[value.raw=/${pattern}/]`, message },
];

// ─── Element ban (AUTHORED only) ───────────────────────────────────────────
//
// Headings, p, blockquote, code, ul/ol/li, a, img and form stay legal: shadcn's
// typeset styles raw HTML. What remains is elements with a real component, where
// a raw tag means someone rebuilt a themed control by hand.
const HAND_ROLLED = {
  button: "Use <Button>. It carries the variant, size and focus-ring tokens.",
  input: "Use <Input> / <Checkbox> / <Switch> / <RadioGroup> / <Slider> / <InputOTP>.",
  textarea: "Use <Textarea>.",
  select: "Use <Select>, or <NativeSelect> when you want the OS control.",
  label: "Use <Label>, or <Field> for a labelled control.",
  table: "Use <Table>.",
  thead: "Use <TableHeader>.",
  tbody: "Use <TableBody>.",
  tfoot: "Use <TableFooter>.",
  tr: "Use <TableRow>.",
  td: "Use <TableCell>.",
  th: "Use <TableHead>.",
  hr: "Use <Separator>.",
  dialog: "Use <Dialog> / <AlertDialog> / <Sheet> / <Drawer>.",
  progress: "Use <Progress>.",
  kbd: "Use <Kbd>.",
};

// eslint-plugin-react already prefixes "<x> is forbidden," — don't repeat it.
const forbidElements = Object.entries(HAND_ROLLED).map(([element, message]) => ({
  element,
  message,
}));

// ─── Lynk rules: type scale and i18n (AUTHORED only) ───────────────────────
//
// Two rules the shadcn preset can't express as a selector ban, so they live in
// a small local plugin. Both read string literals, the same way the colour
// rules do.

// A text size and a font weight in the same class string is a heading or label
// written by hand: the type scale drifting outside <Heading> / <Text>, the way
// bg-blue-500 drifts outside the colour tokens. A size alone (text-xs on a
// badge) or a weight alone (font-medium on a link) stays legal.
const TYPE_SIZE = /(?:^|[\s:])text-(?:xs|sm|base|lg|[2-9]?xl|\[[\d.]+(?:px|rem|em)\])(?=\s|$)/u;
const TYPE_WEIGHT = /(?:^|[\s:])font-(?:thin|extralight|light|normal|medium|semibold|bold|extrabold|black)(?=\s|$)/u;

// The scale itself is defined here and nowhere else.
const TYPE_SCALE_FILE = "src/shared/ui/typography.tsx";

const typeScale = {
  meta: {
    type: "problem",
    docs: { description: "Text size + weight together belong to <Heading> / <Text>." },
    schema: [],
  },
  create(context) {
    const check = (node, value) => {
      if (typeof value === "string" && TYPE_SIZE.test(value) && TYPE_WEIGHT.test(value)) {
        context.report({
          node,
          message:
            "Hand-written type style (text size + font weight). Use <Heading level> or <Text variant> from @/shared/ui/typography. If no level or variant fits, add one there.",
        });
      }
    };
    return {
      Literal: (node) => check(node, node.value),
      TemplateElement: (node) => check(node, node.value.raw),
    };
  },
};

// User-facing text must go through t("…") so the German build has it. Checked:
// text between JSX tags, text-carrying attributes, and toast({ title, description }).
// Strings without a letter ("·", "—", "%", "42") are not text.
const HAS_LETTER = /\p{L}/u;
const TEXT_ATTRIBUTES = new Set([
  "aria-label",
  "aria-description",
  "aria-placeholder",
  "aria-roledescription",
  "alt",
  "placeholder",
  "title",
  "subtitle",
  "description",
  "label",
]);
const TOAST_TEXT_KEYS = new Set(["title", "description", "label"]);
const I18N_MESSAGE =
  'Hardcoded user-facing text. Use t("…") from useI18n() and add the German entry to the DE map in src/lib/i18n.tsx.';

const noLiteralString = {
  meta: {
    type: "problem",
    docs: { description: "User-facing strings go through t()." },
    schema: [
      {
        type: "object",
        properties: { allow: { type: "array", items: { type: "string" } } },
        additionalProperties: false,
      },
    ],
  },
  create(context) {
    const allow = new Set(context.options[0]?.allow ?? []);
    const isText = (value) =>
      typeof value === "string" && HAS_LETTER.test(value) && !allow.has(value.trim());
    const report = (node) => context.report({ node, message: I18N_MESSAGE });
    return {
      JSXText(node) {
        if (isText(node.value)) report(node);
      },
      // {"Save"} or {`Save`} as a child.
      "JSXElement > JSXExpressionContainer > Literal, JSXFragment > JSXExpressionContainer > Literal"(node) {
        if (isText(node.value)) report(node);
      },
      "JSXElement > JSXExpressionContainer > TemplateLiteral, JSXFragment > JSXExpressionContainer > TemplateLiteral"(node) {
        if (node.quasis.some((q) => isText(q.value.raw))) report(node);
      },
      JSXAttribute(node) {
        const name = typeof node.name.name === "string" ? node.name.name : null;
        if (!name || !TEXT_ATTRIBUTES.has(name) || !node.value) return;
        const value =
          node.value.type === "Literal"
            ? node.value.value
            : node.value.type === "JSXExpressionContainer" && node.value.expression.type === "Literal"
              ? node.value.expression.value
              : null;
        if (isText(value)) report(node.value);
      },
      CallExpression(node) {
        const callee = node.callee;
        const name =
          callee.type === "Identifier"
            ? callee.name
            : callee.type === "MemberExpression" && callee.object.type === "Identifier"
              ? callee.object.name
              : null;
        if (name !== "toast") return;
        for (const arg of node.arguments) {
          if (arg.type === "Literal" && isText(arg.value)) report(arg);
          if (arg.type !== "ObjectExpression") continue;
          for (const prop of arg.properties) {
            const key = prop.type === "Property" && (prop.key.name ?? prop.key.value);
            if (TOAST_TEXT_KEYS.has(key) && prop.value.type === "Literal" && isText(prop.value.value))
              report(prop.value);
          }
        }
      },
    };
  },
};

const lynk = { rules: { "type-scale": typeScale, "no-literal-string": noLiteralString } };

